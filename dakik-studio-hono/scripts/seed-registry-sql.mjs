#!/usr/bin/env node
/**
 * seed-registry-sql.mjs
 *
 * Turns the generated registry items in `registry/r/*.json` into a D1 seed:
 * `prisma/seed-registry.sql`. Each (single-file) registry item maps onto one
 * `component_doc` row — the `.tsx` source goes in `code`, and all shadcn
 * registry metadata (type, author, dependencies, registryDependencies,
 * cssVars, css, meta, file path/type) goes in the existing `props` JSON column.
 * No schema migration required.
 *
 * The registry is then served dynamically from these rows (src/routes/registry.ts),
 * so the admin panel's existing ComponentDoc CRUD edits the live registry.
 *
 * Apply it with wrangler (run `bun run build:registry` first if regenerating):
 *   Local:  bunx wrangler d1 execute dakik-studio --local  --file=prisma/seed-registry.sql
 *   Remote: bunx wrangler d1 execute dakik-studio --remote --file=prisma/seed-registry.sql
 *
 * Rows use deterministic ids (`cmp_<slug>`) + `INSERT OR REPLACE`, so re-seeding
 * is idempotent and never touches unrelated component_doc rows.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const R_DIR = resolve(__dirname, "../registry/r");
const OUT_SQL = resolve(__dirname, "../prisma/seed-registry.sql");

/** SQLite single-quoted string literal (only `'` needs escaping; no backslash processing). */
const q = (v) => (v == null ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

async function main() {
  const files = (await readdir(R_DIR)).filter((f) => f.endsWith(".json")).sort();
  if (!files.length) throw new Error(`No items in ${R_DIR} — run bun run build:registry first.`);

  const rows = [];
  for (const file of files) {
    const item = JSON.parse(await readFile(resolve(R_DIR, file), "utf8"));
    const slug = item.name;
    const mainFile = item.files?.[0];
    if (!mainFile) throw new Error(`${slug}: no files[]`);
    if (item.files.length > 1) {
      // Current source registry is 100% single-file; guard so this is loud if upstream changes.
      throw new Error(`${slug}: ${item.files.length} files — extend the seed to use component_file rows.`);
    }

    // Everything the serve route needs to reconstruct the registry item, minus the
    // human-facing columns (title→name, categories[0]→category, description) and the
    // file content (→code).
    const props = {
      type: item.type,
      author: item.author,
      dependencies: item.dependencies,
      registryDependencies: item.registryDependencies,
      cssVars: item.cssVars,
      css: item.css,
      file: { path: mainFile.path, type: mainFile.type, target: mainFile.target },
    };

    rows.push(
      `INSERT OR REPLACE INTO "component_doc" ` +
        `("id","name","slug","category","description","props","code","preview","published","createdAt","updatedAt") VALUES (` +
        [
          q(`cmp_${slug}`),
          q(item.title || slug),
          q(slug),
          q(item.categories?.[0] || "Components"),
          item.description ? q(item.description) : "NULL",
          q(JSON.stringify(props)),
          q(mainFile.content),
          "NULL",
          "true",
          // Prisma (D1) stores DateTime as `YYYY-MM-DD HH:MM:SS.SSS` UTC text.
          `strftime('%Y-%m-%d %H:%M:%f','now')`,
          `strftime('%Y-%m-%d %H:%M:%f','now')`,
        ].join(",") +
        `);`,
    );
  }

  const sql =
    `-- Generated by scripts/seed-registry-sql.mjs — do not edit by hand.\n` +
    `-- Seeds ${rows.length} Dakik Bits registry items into component_doc.\n` +
    `-- Apply: wrangler d1 execute dakik-studio --local|--remote --file=prisma/seed-registry.sql\n\n` +
    `${rows.join("\n")}\n`;

  await writeFile(OUT_SQL, sql);
  console.log(`Wrote ${rows.length} rows → ${OUT_SQL} (${(sql.length / 1024).toFixed(0)} KB)`);
}

main().catch((err) => {
  console.error(`\n✗ ${err.message}`);
  process.exit(1);
});
