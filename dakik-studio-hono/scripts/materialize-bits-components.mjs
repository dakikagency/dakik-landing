#!/usr/bin/env node
/**
 * Materialize the bits registry sources into the frontend so the docs site can
 * render live previews. Reads every `registry/r/*.json` item and writes its
 * files under `src/frontend/bits/` — the directory the `@/` Vite/TS alias
 * points at, mirroring the import layout the components expect:
 *
 *   registry/react/lib/utils.ts        → src/frontend/bits/lib/utils.ts      (@/lib/utils)
 *   registry/react/components/<x>.tsx  → src/frontend/bits/registry/react/components/<x>.tsx
 *   registry/react/hooks/<x>.tsx       → src/frontend/bits/registry/react/hooks/<x>.tsx
 *
 * Run after `build:registry` whenever the registry snapshot changes:
 *   node scripts/materialize-bits-components.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const registryDir = path.join(root, "registry", "r");
const outDir = path.join(root, "src", "frontend", "bits");

/** Registry file path → on-disk path under src/frontend/bits/. */
function targetOf(registryPath) {
	// `@/lib/utils`-style imports expect lib files at the alias root, not under
	// registry/react/lib/.
	if (registryPath.startsWith("registry/react/lib/")) {
		return registryPath.replace("registry/react/lib/", "lib/");
	}
	return registryPath;
}

const BANNER =
	"// GENERATED by scripts/materialize-bits-components.mjs — do not edit.\n// Source of truth: registry/r/*.json (see scripts/build-bits-registry.mjs).\n\n";

/** Registry `css` JSON (css-in-js style nesting) → plain CSS text. */
function cssText(node, indent = "") {
	let out = "";
	for (const [key, value] of Object.entries(node)) {
		if (typeof value === "string") {
			out += `${indent}${key}: ${value};\n`;
		} else {
			out += `${indent}${key} {\n${cssText(value, `${indent}\t`)}${indent}}\n`;
		}
	}
	return out;
}

fs.rmSync(outDir, { recursive: true, force: true });

let written = 0;
let css =
	"/* GENERATED by scripts/materialize-bits-components.mjs — do not edit. */\n/* Per-item `css` blocks (keyframes etc.) the shadcn CLI would inject. */\n";
for (const file of fs.readdirSync(registryDir).sort()) {
	if (!file.endsWith(".json")) continue;
	const item = JSON.parse(fs.readFileSync(path.join(registryDir, file), "utf8"));
	for (const f of item.files ?? []) {
		const target = path.join(outDir, targetOf(f.path));
		fs.mkdirSync(path.dirname(target), { recursive: true });
		// chart's types track recharts v3, but the preview pins recharts v2 —
		// rolldown (Vite 8) miscompiles v3's es-toolkit/compat dep into
		// self-referential `var t=t()` code that throws at runtime.
		const header =
			item.name === "chart" ? `${BANNER}// @ts-nocheck\n\n` : BANNER;
		fs.writeFileSync(target, header + f.content);
		written++;
	}
	if (item.css) css += `\n/* ${item.name} */\n${cssText(item.css)}`;
}

fs.writeFileSync(path.join(outDir, "bits.css"), css);
console.log(
	`Materialized ${written} files + bits.css into ${path.relative(root, outDir)}/`,
);
